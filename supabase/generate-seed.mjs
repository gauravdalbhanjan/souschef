// Generates supabase/seed_recipes.sql from the bundled recipe dataset + steps.
// Usage:  node supabase/generate-seed.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { canonicalOf, STAPLES } from '../lib/normalize.js'
import { stepsFor } from '../lib/steps.js'

const __dirname = dirname(fileURLToPath(import.meta.url))
const recipes = JSON.parse(readFileSync(join(__dirname, '..', 'lib', 'recipes.json'), 'utf8'))

const q = (s) => `'${String(s ?? '').replace(/'/g, "''")}'`
const out = [
  '-- Generated by supabase/generate-seed.mjs. Safe to re-run (upserts by slug).',
  'begin;',
]

for (const r of recipes) {
  const steps = JSON.stringify(stepsFor(r.slug, r.name, r.ingredients))
  out.push(
    `insert into public.recipes (slug,name,image,time_mins,kcal,servings,description,steps,source) values (` +
    `${q(r.slug)},${q(r.name)},${q(r.image)},${r.time_mins},${r.kcal},${r.servings},${q(r.description)},` +
    `$steps$${steps}$steps$::jsonb,${q(r.source || 'bundled')}) ` +
    `on conflict (slug) do update set name=excluded.name,image=excluded.image,time_mins=excluded.time_mins,` +
    `kcal=excluded.kcal,servings=excluded.servings,description=excluded.description,steps=excluded.steps,source=excluded.source;`,
  )
  out.push(`delete from public.recipe_ingredients where recipe_id = (select id from public.recipes where slug = ${q(r.slug)});`)
  const rows = r.ingredients.map(ing => {
    const canonical = canonicalOf(ing.display)
    const staple = ing.staple || STAPLES.has(canonical)
    return `((select id from public.recipes where slug = ${q(r.slug)}),${q(canonical)},${q(ing.display)},` +
      `${Number(ing.quantity) || 0},${q(ing.unit || 'unit')},${ing.optional ? 'true' : 'false'},${staple ? 'true' : 'false'})`
  })
  out.push(`insert into public.recipe_ingredients (recipe_id,canonical,display,quantity,unit,optional,staple) values\n  ${rows.join(',\n  ')};`)
}

out.push('commit;')
writeFileSync(join(__dirname, 'seed_recipes.sql'), out.join('\n') + '\n')
console.log(`Wrote supabase/seed_recipes.sql (${recipes.length} recipes)`)
